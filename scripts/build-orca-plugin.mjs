// Builds the browser renderer for the Orca custom editor in orca-plugin/:
// bundles src/markdownit (the same plugin the VS Code extension uses), markdown-it,
// media/*.css and media/preview.js into one ES module the editor imports.
//
// Usage: node scripts/build-orca-plugin.mjs
//
// The output (orca-plugin/editor/vendor/gitbook-renderer.js) is generated and
// gitignored; Orca reloads a dev-loaded plugin as soon as it changes.

import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pluginDir = path.join(projectRoot, 'orca-plugin');
const outfile = path.join(pluginDir, 'editor', 'vendor', 'gitbook-renderer.js');

// The editor frame has no Node. The renderer only needs node:fs for its
// default file reader (replaced by the editor's own reader) and node:path for
// path maths, which pathe covers.
const nodeShims = {
  name: 'node-shims',
  setup(b) {
    b.onResolve({ filter: /^node:(fs|path)$/ }, (args) => ({ path: args.path, namespace: 'node-shim' }));
    b.onLoad({ filter: /.*/, namespace: 'node-shim' }, (args) =>
      args.path === 'node:fs'
        ? { contents: 'export function readFileSync() { throw new Error("no file system in the editor"); }', loader: 'js' }
        : {
            contents: "import * as p from 'pathe'; export * from 'pathe'; export const posix = p; export const win32 = p; export default { ...p, posix: p, win32: p };",
            loader: 'js',
            resolveDir: projectRoot,
          },
    );
  },
};

await build({
  entryPoints: [path.join(pluginDir, 'src', 'renderer-entry.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  outfile,
  loader: { '.css': 'text' },
  plugins: [nodeShims],
  legalComments: 'none',
  minify: true,
  logLevel: 'warning',
  banner: { js: '// Generated by scripts/build-orca-plugin.mjs — do not edit.' },
});

const code = fs.readFileSync(outfile, 'utf8');
// Orca refuses eval in editor frames.
if (/\beval\s*\(|new Function\s*\(/.test(code)) {
  console.error('build-orca-plugin: output contains eval/new Function, which Orca refuses');
  process.exit(1);
}
console.log(`Built ${path.relative(projectRoot, outfile)} (${(code.length / 1024).toFixed(0)} KB)`);
